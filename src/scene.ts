/**
 * 消息场景判据（2026-10-13 · auto-recall 分场景处置的地基）
 *
 * **为什么需要**（主人 2026-10-13 22:13 追问「泛用性和便捷性呢」后实测）：
 * 用主人**真实说过的话**（12 条）量现行 auto-recall——通过门槛仅 **4/12 = 33.3%**，
 * 而分场景看差异极大：
 *
 * | 场景 | 通过率 | 平均 top1 |
 * |---|---|---|
 * | 决策/判断型 | **100%** | 88.5 |
 * | 任务指令型 | 33.3% | 56.3 |
 * | 指代密集型 | 20% | 18.5 |
 * | 状态追踪型 | **0%** | 18.1 |
 * | 闲聊型 | 0% | 11.5 |
 *
 * ⇒ **单一门槛无法同时服务五类**：门槛 30 恰好是「闲聊清零」的临界点
 * （实测：阈 20 时闲聊类 **40% 会注入**，阈 30 时 **0%**）⇒ 不能降门槛。
 * 正解是**按场景分处置**（主人定调「分场景定」）。
 *
 * **判据边界（重要）**：本模块只做**语言事实**级判断
 * （「嗯」有没有检索意图 = 语言事实），**不做价值判断**
 * （「这条记忆值不值得看」归主体，见 AGENTS.md §2.1「机制只送信号，决策归我」）。
 *
 * **标定**：32 条金标准，准确率 **90.6%（29/32）**。剩余 3 例的性质见 §已知边界。
 */

/** 场景类型 */
export type MessageScene =
  /** 闲聊/元指令：无检索意图，**不该检索**（注入即纯噪音） */
  | 'chitchat'
  /** 指代密集：「那个」「昨天」——查询词在记忆里根本不存在，需**时间窗/上下文** */
  | 'deictic'
  /** 状态追踪：「做完了吗」——答案在近期，需**时间窗** */
  | 'tracking'
  /** 任务/决策：具体内容，**正常检索**（实测该类表现最好） */
  | 'task'

export interface SceneDecision {
  scene: MessageScene
  /** 判据说明（可复核：说清「为什么判成这类」） */
  evidence: string
}

/** 中文停用词（与 search.ts 同表，判据单一真源） */
const STOP_WORDS = new Set([
  '的', '了', '吗', '呢', '吧', '啊', '呀', '嘛', '哦', '嗯',
  '是', '在', '有', '和', '与', '或', '及', '跟', '并', '且',
  '我', '你', '他', '她', '它', '们', '这', '那', '个', '之',
  '到', '从', '对', '为', '把', '被', '让', '给', '向', '以',
  '一个', '一些', '这个', '那个', '什么', '怎么', '为什么', '如何', '哪里',
  '地', '得', '着', '过',
])

/**
 * 元指令：明确把决定权交回（无检索意图）。
 *
 * ⚠ **必须是整句匹配，不能裸子串**（2026-10-13 测试抓出的严重缺陷）：
 * 首版用 `t.includes('好')` / `t.includes('行')` ⇒
 * 「那个修**好**了吗」被判 chitchat、「我觉得还是要**行**重做」…
 * 实测：「我觉得还是要**进行**重做」因含 `行` 被判 chitchat
 * ⇒ **该检索却被抑制**（最坏一类错：我要用的东西没来，而且我无从察觉）。
 * ⇒ 极短词（≤2 字）一律**整句等值**匹配；长词才允许子串。
 *
 * ⚠ **不要把 `继续`/`接着` 挪进 SUBSTRING**（2026-10-13 走过一次弯路）：
 * 我当时想用它挡守护通知「…请继续。」，但那**追错了对象**——
 * 该消息的问题不是「继续」这个词，而是**它压根不是主人消息**（见 `SYSTEM_NOTICE_PREFIXES`）。
 * 若挪进 SUBSTRING，「继续分析这个项目」这类**真任务**会被误抑制（最坏一类错）。
 */
const META_EXACT = ['好', '行', '嗯', '哦', '可以', '随便', '都行', '都可以', '继续', '接着']
const META_SUBSTRING = ['你自己决定', '你决定', '你看着办', '听你的', '然后呢']

/**
 * 系统通知前缀（**不该触发 auto-recall**）。
 *
 * **为什么单独处理**（2026-10-13 实测抓到）：守护重启通知
 * `[守护] web 已重启（22:19:22）。请继续。` 与主人消息**走同一条路径**进入 auto-recall。
 * 实测该消息 top1=26.3 ⇒ 在 task 门槛（20）下**会注入**，而注入的恰是
 * 「重启链两个已知脾气」等**与当前工作无关**的旧记忆（当时我在部署记忆插件，
 * 不是排查重启）⇒ **纯噪音**。
 *
 * **判据**：前缀形如 `[<来源>]` 的方括号通知，来自插件/守护而非主人；
 * 它们的内容是**系统事件**，不含检索意图。⇒ 一律短路（返回 chitchat）。
 */
const SYSTEM_NOTICE_PREFIXES = ['[守护]', '[系统]', '[system]', '[guardian]', '[watch]']

/** 状态追踪语（问某事的进展） */
const TRACKING_PHRASES = [
  '做完了吗', '好了吗', '怎么样了', '进展', '完成了吗', '搞定了吗', '搞定了吧',
  '修好了吗', '跑完了吗', '解决了吗', '弄好了吗', '弄完了吗',
]

/**
 * 指代词（跨句指代记忆的）。
 *
 * ⚠ **已知边界**：本表不区分「句内指代」与「跨句指代」——
 * 「分析这个开源项目」里的「这个」指同句宾语，不是指记忆，但会被判成 deictic。
 * 代价评估：deictic 的处置是「加时间窗」，对这类消息**无害**（只是多一次时间范围收窄）；
 * 修它需要句法分析，收益不抵成本。**不修，但如实记录**。
 */
const DEIXIS_WORDS = [
  '那个', '这条', '这个', '这些', '那些', '刚才', '刚刚', '昨天', '今天', '明天',
  '上次', '那次', '上面', '前面', '之前提的', '你说的', '刚才那个',
]

/**
 * 判一条消息属于哪个场景（纯函数，可离线标定）。
 *
 * **判定顺序**（从「不该检索」到「该检索」，避免误判后放行）：
 * ① 元指令 → chitchat
 * ② 状态追踪 → tracking（**必须先于极短判定**，见下）
 * ③ 极短且非疑问（≤4 字）→ chitchat
 * ④ 含指代词 → deictic
 * ⑤ 其余 → task
 *
 * ⚠ **顺序纪律（首版踩过，2026-10-13）**：把「极短」判在「tracking」之前时，
 * 「跑完了吗」（5 字）被当极短吃掉 → 判成 chitchat → **该检索却被抑制**。
 * 抑制错（我要用的东西没来）比放行错（多点噪音）**更坏**——前者我无从察觉。
 * 故 tracking 前置。
 *
 * @param text - 主人消息原文
 * @returns 场景 + 判据说明
 */
export function classifyMessage(text: string): SceneDecision {
  const t = (text ?? '').trim()
  if (t.length === 0) return { scene: 'chitchat', evidence: '空消息' }

  // ⓪ 系统通知（**判在最前**）：守护/插件事件不是主人的检索意图
  for (const prefix of SYSTEM_NOTICE_PREFIXES) {
    if (t.startsWith(prefix)) return { scene: 'chitchat', evidence: `系统通知「${prefix}」` }
  }

  // ① 元指令：**短词整句等值**（防子串误伤，见 META_EXACT 注释）+ 长词子串
  const bareMeta = t.replace(/[\s，。、；：？！,.;:?!"'（）()【】[\]]/g, '')
  for (const phrase of META_EXACT) {
    if (bareMeta === phrase) return { scene: 'chitchat', evidence: `元指令「${phrase}」(整句)` }
  }
  for (const phrase of META_SUBSTRING) {
    if (t.includes(phrase)) return { scene: 'chitchat', evidence: `元指令「${phrase}」` }
  }

  // ② 状态追踪（**在极短判定之前**——顺序纪律见函数注释）
  for (const phrase of TRACKING_PHRASES) {
    if (t.includes(phrase)) return { scene: 'tracking', evidence: `追踪语「${phrase}」` }
  }

  // ③ 极短且非疑问：去掉标点后 ≤ 4 字符
  const bare = bareMeta
  if (bare.length <= 4 && !/[？?]$/.test(t)) {
    return { scene: 'chitchat', evidence: `极短(${bare.length}字)` }
  }

  // ④ 指代密集
  for (const word of DEIXIS_WORDS) {
    if (t.includes(word)) return { scene: 'deictic', evidence: `指代「${word}」` }
  }

  return { scene: 'task', evidence: '具体内容' }
}

/**
 * 场景 → auto-recall 的最低分门（`worthInjecting` 用）。
 *
 * **取值依据**（2026-10-13 实测，12 条主人真实消息 + 分场景门槛敏感性）：
 *
 * | 场景 | 处置 | 门槛 | 理由 |
 * |---|---|---|---|
 * | `chitchat` | **不检索** | ∞ | 无检索意图，检索结果必然是噪音；直接短路省算力 |
 * | `deictic` | 正常检索 | 20 | 见 §时间窗未做 |
 * | `tracking` | 正常检索 | 20 | 同上 |
 * | `task` | 正常检索 | **20** | 该类实测阈 20 时 100% 通过、阈 30 时仅 33%——任务是**新**的，带上相关经验是净收益 |
 *
 * ⚠ **为什么 chitchat 用 `Infinity` 而不是高门槛**：门槛只能「压低概率」，
 * 而闲聊类**不该有非零概率**（实测「你自己决定吧」top1=22.9，「那么泛用性呢」=22.2，
 * 都低于 30 但**高于 20**）⇒ 只有短路才能保证零注入。
 *
 * ⚠ **deictic/tracking 的时间窗机制尚未实现**（2026-10-13 第一步只做门槛分化）：
 * 这两类先用与 task 相同的门槛——**不假装解决了**，时间窗是第二步。
 */
export function thresholdForScene(scene: MessageScene): number {
  if (scene === 'chitchat') return Number.POSITIVE_INFINITY
  return 20
}
